def test_g00_02_f01_rename_keeps_id_constitution_and_policy():
    p=project(); renamed=replace(p,display_name='Renamed')
    assert renamed.project_id==p.project_id
    assert renamed.constitution_ref==p.constitution_ref
    assert renamed.source_policy_ref==p.source_policy_ref
    assert validate_project(renamed).ok


def test_g00_02_f02_repository_policy_blocks_unknown_repository():
    p=project(); s=cut(p,repo=RepositoryId('github','outsider/rogue'))
    result=check_source_membership(p,s)
    assert result.status is MembershipStatus.DENIED
    assert result.code=='SOURCE_REPOSITORY_DENIED'


@pytest.mark.parametrize('mode',[StorageMode.EMBEDDED,StorageMode.SIDECAR,StorageMode.FEDERATED])
def test_g00_02_f03_storage_modes_are_declarative(mode):
    p=project(mode=mode)
    assert validate_storage_mode(p.storage).ok
    assert p.storage.mode is mode
    if mode is StorageMode.SIDECAR:
        assert p.storage.authority_repository not in p.storage.repositories


def test_g00_02_f03_federation_requires_distinct_owners():
    p=project(mode=StorageMode.FEDERATED)
    with pytest.raises(ValueError,match='FEDERATED_AUTHORITY_INCOMPLETE'):
        StorageDescriptor(StorageMode.FEDERATED,p.storage.authority_repository,
                          p.storage.repositories,(('source',p.storage.repositories[0]),))


def test_g00_02_f04_explicit_project_identity_in_views():
    a=project();b=project('project-beta')
    assert check_project_membership(a,entity(b.project_id,EntityKind.OBLIGATION,'same')).status is MembershipStatus.REQUIRES_APPROVAL
    assert check_project_membership(b,entity(b.project_id,EntityKind.OBLIGATION,'same')).allowed


def test_g00_02_f05_foreign_refs_need_import_descriptor_and_trusted_grants():
    a=project();b=project('project-beta');s=cut(b)
    assert check_source_membership(a,s).status is MembershipStatus.REQUIRES_APPROVAL
    grant=ApprovedSourceImport(a.project_id,s.ref,s.repository,s.path,entity(a.project_id,EntityKind.DECISION,'approval'))
    assert check_source_membership(a,s,TrustedImportGrants((grant,))).allowed
    # The grant is externally supplied evidence, never generated by domain.
    assert check_source_membership(a,s).status is MembershipStatus.REQUIRES_APPROVAL


def test_g00_02_f06_import_scope_never_spills_to_other_cut_path_or_repo():
    a=project();b=project('project-beta');s=cut(b)
    g=TrustedImportGrants((ApprovedSourceImport(a.project_id,s.ref,s.repository,s.path,
                              entity(a.project_id,EntityKind.DECISION,'approval')),))
    other=cut(b,name='source-second',path='spec/other.gsl')
    mutated=cut(b,path='spec/other.gsl')
    assert not check_source_membership(a,other,g).allowed
    assert check_source_membership(a,mutated,g).code=='UNAPPROVED_IMPORT_SCOPE'


def test_g00_02_f07_pinned_constitution_and_source_policy_versions():
    p=project();old=p.source_policy_ref
    different=entity(p.project_id,EntityKind.SOURCE_POLICY,'policy')
    with pytest.raises(ValueError,match='PROJECT_POLICY_REVISION_MISMATCH'):
        replace(p,source_policy_ref=different)
    assert p.source_policy_ref==old


def test_g00_02_f08_federated_repos_preserve_independent_commits():
    p=project(mode=StorageMode.FEDERATED)
    first=cut(p,name='first',repo=p.storage.repositories[0],commit='1'*40)
    second=cut(p,name='second',repo=p.storage.repositories[1],commit='2'*40)
    u=universe(p,(first,second))
    view=build_readonly_project_view(p,u,{first.ref:first,second.ref:second})
    assert view.ok,view.diagnostics
    assert {s.commit for s in view.value.sources}=={'1'*40,'2'*40}


def test_g00_02_f09_same_human_aliases_separate_project_namespaces():
    a=project(); b=project('project-beta')
    ra=entity(a.project_id,EntityKind.OBLIGATION,'same')
    rb=entity(b.project_id,EntityKind.OBLIGATION,'same')
    idx=AliasIndex()
    idx=bind_alias(idx,ra,Alias('Human Name'),cut(a).ref).index
    idx=bind_alias(idx,rb,Alias('Human Name'),cut(b).ref).index
    assert resolve_alias(idx,a.project_id,EntityKind.OBLIGATION,Alias('Human Name')).value==ra
    assert resolve_alias(idx,b.project_id,EntityKind.OBLIGATION,Alias('Human Name')).value==rb


def test_g00_02_f10_readonly_project_snapshot_no_input_mutations():
    p=project();s=cut(p);u=universe(p,(s,));catalog={s.ref:s}
    before=dict(catalog)
    a=build_readonly_project_view(p,u,catalog)
    b=build_readonly_project_view(p,u,catalog)
    assert a.ok and b.ok and a.value==b.value
    assert catalog==before and a.value.definition==p and a.value.source_universe==u
    with pytest.raises(Exception):
        a.value.sources+=(s,)


